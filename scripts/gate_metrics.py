"""Measure and record wall time for every ``./gate.sh`` arm.

The output, ``docs/_generated/gate-measurements.md``, is generated: never edit a
number in it by hand. Refresh it on the host that ran the gate:

    uv run --no-sync python scripts/gate_metrics.py refresh

    uv run --no-sync python scripts/gate_metrics.py refresh --only lint,test

    uv run --no-sync python scripts/gate_metrics.py refresh --label "baseline"

Each refresh appends a dated entry (host, commit, per-arm status and seconds) and
re-renders the file; the newest entry is the table at the top. `--only` instead
re-measures the named arms inside the newest entry, so the table still describes a
complete run; it refuses when HEAD no longer matches that entry's commit. `redraw`
re-renders the file from the recorded payload without measuring anything, for a
wording-only change. History is carried in a trailing HTML comment as JSON, so the
document stays a single self-describing file.
"""

from __future__ import annotations

import argparse
import json
import platform
import re
import subprocess
import sys
import time
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "_generated" / "gate-measurements.md"
PAYLOAD = re.compile(r"<!-- gate-metrics: (\[.*?\]) -->", re.DOTALL)
MAX_HISTORY = 10
NOTES = {
    "lint": "ruff check + ruff format --check",
    "test": "pytest with the pyproject coverage gate",
    "test-fast": "package-module suites, --no-cov, real_api deselected",
    "build": "uv build (sdist + wheel)",
    "program": "edition scaffold, approved public tree, site render",
    "site": "site render from the verified public tree",
    "docs": "relative links, docs index, gate-arm list",
    "gnn": "pinned parser install + verification (uv cache warm)",
}


def arms() -> list[str]:
    out = subprocess.run(
        ["./gate.sh", "list"], cwd=ROOT, check=True, capture_output=True, text=True
    )
    return [line.strip() for line in out.stdout.splitlines() if line.strip()]


def summarize(output: str) -> str:
    """Pull pytest counts and coverage out of an arm's output, when present."""
    parts = []
    for pattern, label in (
        (r"(\d+) passed", "passed"),
        (r"(\d+) skipped", "skipped"),
        (r"(\d+) failed", "failed"),
        (r"(\d+) error", "errors"),
    ):
        match = re.search(pattern, output)
        if match:
            parts.append(f"{match.group(1)} {label}")
    coverage = re.search(r"Total coverage: (\d+(?:\.\d+)?)%", output) or re.search(
        r"^TOTAL\s+\d+\s+\d+\s+(\d+(?:\.\d+)?)%", output, re.MULTILINE
    )
    if coverage:
        parts.append(f"coverage {coverage.group(1)}%")
    return ", ".join(parts)


def run_arm(arm: str) -> dict[str, object]:
    started = time.monotonic()
    result = subprocess.run(["./gate.sh", arm], cwd=ROOT, capture_output=True, text=True)
    elapsed = time.monotonic() - started
    return {
        "arm": arm,
        "status": "pass" if result.returncode == 0 else f"fail ({result.returncode})",
        "seconds": round(elapsed, 2),
        "notes": summarize(result.stdout + result.stderr),
    }


def load_history() -> list[dict]:
    if not DOC.exists():
        return []
    match = PAYLOAD.search(DOC.read_text(encoding="utf-8"))
    return json.loads(match.group(1)) if match else []


def environment() -> dict[str, str]:
    uv = subprocess.run(["uv", "--version"], check=True, capture_output=True, text=True)
    head = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    return {
        "timestamp": datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC"),
        "commit": head.stdout.strip(),
        "host": platform.platform(),
        "python": platform.python_version(),
        "uv": uv.stdout.split()[1],
    }


def resolve_commit(ref: str) -> str:
    """Return the full commit id for a stored revision, or the ref when unknown."""
    result = subprocess.run(
        ["git", "rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    return result.stdout.strip() or ref


def render(history: list[dict]) -> str:
    newest = history[-1]
    lines = [
        "# Gate measurements",
        "",
        "<!-- generated by scripts/gate_metrics.py refresh; do not edit -->",
        "",
        "Wall time per `./gate.sh` arm on the host that last refreshed this file.",
        "An arm is one documented command; CI runs `lint`, `test`, `build`, `program`,",
        "`site`, `docs` and `gnn`, and `test-fast` is local-only. See",
        "[development](../development.md) and [gate.sh](../../gate.sh).",
        "",
        f"Latest run: {newest['timestamp']} at commit `{newest['commit']}` on",
        f"{newest['host']}, Python {newest['python']}, uv {newest['uv']}"
        + (f" ({newest['label']})." if newest.get("label") else "."),
        "",
        "| Arm | Status | Wall time (s) | Notes |",
        "| --- | --- | --- | --- |",
    ]
    for entry in newest["arms"]:
        note = entry["notes"] or NOTES.get(str(entry["arm"]), "")
        lines.append(f"| `{entry['arm']}` | {entry['status']} | {entry['seconds']} | {note} |")
    lines += [
        "",
        "Wall time is one run on this host, not a benchmark: a cold page cache, a",
        "`uv sync`, or a busy machine changes it. Test counts and coverage are from",
        "the same run; an absent count means the arm does not run pytest.",
        "",
        "## History",
        "",
    ]
    for entry in reversed(history[:-1]):
        label = f" — {entry['label']}" if entry.get("label") else ""
        lines += [
            f"### {entry['timestamp']}{label} (commit `{entry['commit']}`)",
            "",
            "| Arm | Status | Wall time (s) | Notes |",
            "| --- | --- | --- | --- |",
        ]
        for arm_entry in entry["arms"]:
            note = arm_entry["notes"] or NOTES.get(str(arm_entry["arm"]), "")
            lines.append(
                f"| `{arm_entry['arm']}` | {arm_entry['status']} | "
                f"{arm_entry['seconds']} | {note} |"
            )
        lines.append("")
    payload = json.dumps(history[-MAX_HISTORY:], indent=None, sort_keys=True)
    lines += [f"<!-- gate-metrics: {payload} -->", ""]
    return "\n".join(lines)


def refresh(label: str | None, only: list[str]) -> int:
    selected = only or arms()
    unknown = [arm for arm in selected if arm not in arms()]
    if unknown:
        print(f"unknown arm(s): {', '.join(unknown)}", file=sys.stderr)
        return 2
    history = load_history()
    DOC.parent.mkdir(parents=True, exist_ok=True)

    def write() -> None:
        DOC.write_text(render(history), encoding="utf-8")

    if only and history:
        # Re-measure named arms inside the newest entry instead of appending a
        # partial one, so the top table still describes a complete run. The entry's
        # provenance must still hold: a partial refresh at a different revision
        # would attribute these numbers to the wrong commit.
        entry = history[-1]
        current = environment()
        if resolve_commit(str(entry.get("commit"))) != resolve_commit(current["commit"]):
            print(
                f"refusing partial refresh: entry is at {entry.get('commit')}, "
                f"HEAD is {current['commit']}; run a full refresh",
                file=sys.stderr,
            )
            return 2
        rows = {arm_entry["arm"]: arm_entry for arm_entry in entry["arms"]}
        for arm in selected:
            rows.setdefault(
                arm, {"arm": arm, "status": "not measured", "seconds": 0.0, "notes": ""}
            )
        order = [arm for arm in arms() if arm in rows]
        order += [arm for arm in rows if arm not in order]
        entry["arms"] = [rows[arm] for arm in order]
        for key in ("timestamp", "host", "python", "uv"):
            entry[key] = current[key]
        # Persist the synthesized table before measuring: an arm that reads the
        # document (docs checks the arm list) must already see its own row.
        write()
        for arm in selected:
            entry["arms"][order.index(arm)] = run_arm(arm)
            write()
            result = entry["arms"][order.index(arm)]
            print(f"{arm}: {result['status']} in {result['seconds']}s", flush=True)
        print(DOC.relative_to(ROOT))
        return 0 if all(arm_entry["status"] == "pass" for arm_entry in entry["arms"]) else 1

    entry = environment()
    entry["label"] = label or ""
    entry["arms"] = [
        {"arm": arm, "status": "not measured", "seconds": 0.0, "notes": ""} for arm in selected
    ]
    history.append(entry)

    # Write before and after each arm: a long arm leaves an explicit "not measured"
    # row instead of a stale document, and the docs arm sees every arm name.
    write()
    for index, arm in enumerate(selected):
        entry["arms"][index] = run_arm(arm)
        write()
        result = entry["arms"][index]
        print(f"{arm}: {result['status']} in {result['seconds']}s", flush=True)
    print(DOC.relative_to(ROOT))
    return 0 if all(arm_entry["status"] == "pass" for arm_entry in entry["arms"]) else 1


def record(label: str, path: Path) -> int:
    """Append an externally measured entry (for example a pre-gate baseline)."""
    data = json.loads(path.read_text(encoding="utf-8"))
    history = load_history()
    entry = environment()
    entry["label"] = label
    for key in ("commit", "timestamp", "host", "python", "uv"):
        entry[key] = data.get(key, entry[key])
    entry["arms"] = data["arms"]
    history.append(entry)
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text(render(history), encoding="utf-8")
    print(DOC.relative_to(ROOT))
    return 0


def redraw() -> int:
    """Re-render the document from its recorded payload without measuring."""
    history = load_history()
    if not history:
        print(f"no recorded measurements in {DOC.relative_to(ROOT)}", file=sys.stderr)
        return 2
    DOC.write_text(render(history), encoding="utf-8")
    print(DOC.relative_to(ROOT))
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    refresh_parser = sub.add_parser("refresh", help="run arms and write the document")
    refresh_parser.add_argument("--label", help="human label for this entry")
    refresh_parser.add_argument("--only", help="comma-separated arms to measure", default="")
    record_parser = sub.add_parser("record", help="append a measured entry from a JSON file")
    record_parser.add_argument("--label", required=True, help="human label for this entry")
    record_parser.add_argument("--file", required=True, type=Path, help="JSON measurement file")
    sub.add_parser("redraw", help="re-render the document from the recorded payload")
    args = parser.parse_args()
    if args.command == "record":
        return record(args.label, args.file)
    if args.command == "redraw":
        return redraw()
    only = [arm.strip() for arm in args.only.split(",") if arm.strip()]
    return refresh(args.label, only)


if __name__ == "__main__":
    sys.exit(main())
